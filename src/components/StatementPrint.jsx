// StatementPrint — the one printable statement document for KopaBook.
//
// Renders a statement from { business, title, period, lines, totals,
// closingBalance, footer }. Used by History ("Print statement"), the
// Sales history view, the CustomerDetail statement section and (through
// the shared print CSS) the Receipt page.
//
//   business: { name, phone, email, telegram, address } — only the
//     contact fields the owner chose to show are passed in; the
//     component prints what it is given.
//   title: e.g. "Statement" or "Customer statement — Favour".
//   period: e.g. "1 Nov 2026 to 5 Nov 2026".
//   lines: [{ date, description, amount }] — amount is SIGNED: positive
//     raises the balance, negative lowers it, null leaves it unchanged.
//     The running balance is computed here from openingBalance (default 0).
//   totals: [{ label, amount }] — labelled rows for the totals block,
//     e.g. Total sales / Total payments. Pass null to show only the
//     closing balance.
//   closingBalance: overrides the computed closing balance when the
//     caller knows it (e.g. a customer ledger balance). Otherwise the
//     computed value is shown.
//   footer: extra footer line (optional), e.g. the business tagline.
//
// A customer-facing statement NEVER shows cost or profit: this component
// has no cost or profit props and renders nothing but the lines, totals
// and footer it is given. Callers must pass sale totals, never cost.
//
// Print: the parent renders this inside a `.print-only` wrapper (hidden
// on screen, shown in print) and calls window.print(). Styling lives in
// src/print.css, imported here so every user of this component gets it.
import { computeStatement, round2 } from "../lib/statement";
import { fmt } from "../lib/api";
import "../print.css";

export default function StatementPrint({ business, title, period, lines, totals, closingBalance, openingBalance, footer }) {
  const biz = business || {};
  const computed = computeStatement(openingBalance || 0, lines || []);
  const closing = closingBalance === undefined || closingBalance === null
    ? computed.closingBalance
    : round2(closingBalance);
  const generatedAt = new Date().toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric" });
  const contact = [biz.phone, biz.email, biz.telegram].filter(Boolean).join(" · ");

  return (
    <div className="statement-print">
      <div className="statement-head">
        <div className="statement-biz">{biz.name || "My Business"}</div>
        {biz.address && <div className="statement-sub">{biz.address}</div>}
        {contact && <div className="statement-sub">{contact}</div>}
        <div className="statement-title">{title || "Statement"}</div>
        {period && <div className="statement-sub">{period}</div>}
      </div>

      <table className="statement-table">
        <thead>
          <tr><th>Date</th><th>Description</th><th className="num">Amount</th><th className="num">Balance</th></tr>
        </thead>
        <tbody>
          <tr className="statement-opening">
            <td>—</td><td>Opening balance</td><td className="num">—</td><td className="num">{fmt(computed.openingBalance)}</td>
          </tr>
          {computed.lines.map((l, i) => (
            <tr key={i}>
              <td style={{ whiteSpace: "nowrap" }}>{l.date || ""}</td>
              <td>{l.description}</td>
              <td className="num">{l.amount === null ? "—" : fmt(l.amount)}</td>
              <td className="num">{fmt(l.balance)}</td>
            </tr>
          ))}
          {computed.lines.length === 0 && (
            <tr><td colSpan={4} style={{ textAlign: "center", padding: 16 }}>No entries in this period.</td></tr>
          )}
        </tbody>
      </table>

      <div className="statement-totals">
        {(totals || []).map((t, i) => (
          <div className="statement-total-row" key={i}>
            <span>{t.label}</span><span>{fmt(t.amount)}</span>
          </div>
        ))}
        <div className="statement-total-row statement-closing">
          <span>Closing balance</span><span>{fmt(closing)}</span>
        </div>
      </div>

      <div className="statement-footer">
        {footer && <div>{footer}</div>}
        <div>Generated by KopaBook · {generatedAt}</div>
        <div className="statement-page-number" />
      </div>
    </div>
  );
}
